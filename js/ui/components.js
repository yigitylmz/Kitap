/**
 * Toast Bildirim Sistemi (Undo geri alma destekli)
 * @param {string} message 
 * @param {object} [options={}]
 * @param {Function} [options.undoAction]
 * @param {number} [options.duration=3200]
 * @param {'info' | 'success' | 'error'} [options.type='info']
 */
export function showToast(message, { undoAction = null, duration = 3200, type = 'info' } = {}) {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type} ${undoAction ? 'toast-undo' : ''}`;

  const msgSpan = document.createElement('span');
  msgSpan.textContent = message;
  toast.appendChild(msgSpan);

  if (undoAction) {
    const undoBtn = document.createElement('button');
    undoBtn.className = 'toast-btn';
    undoBtn.textContent = 'Geri Al';
    undoBtn.onclick = () => {
      try { undoAction(); } catch (_) {}
      toast.remove();
    };
    toast.appendChild(undoBtn);
  }

  container.appendChild(toast);

  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateY(8px)';
    toast.style.transition = 'all 0.25s ease';
    setTimeout(() => toast.remove(), 260);
  }, duration);
}

/**
 * Modal ve Bottom Sheet Yöneticisi
 * @param {string} contentHtml 
 * @param {object} [options={}]
 * @param {string} [options.title='']
 * @param {Function} [options.onClose]
 * @param {string} [options.className='']
 * @returns {HTMLElement} Modal root elementi
 */
export function openModal(contentHtml, { title = '', onClose = null, className = '' } = {}) {
  closeModal(); // Açık olan eski modalı kapat

  const backdrop = document.createElement('div');
  backdrop.id = 'active-modal-backdrop';
  backdrop.className = `modal-backdrop ${className}`;

  backdrop.innerHTML = `
    <div class="bottom-sheet" role="dialog" aria-modal="true">
      <div class="sheet-handle-bar">
        <div class="sheet-handle"></div>
      </div>
      <div class="sheet-header">
        <h3 class="sheet-title">${title}</h3>
        <button class="sheet-close-btn" id="modal-close-x" aria-label="Kapat">
          ${icons.close}
        </button>
      </div>
      <div class="sheet-body" id="modal-sheet-body">
        ${contentHtml}
      </div>
    </div>
  `;

  document.body.appendChild(backdrop);

  // Animasyonu tetikle
  requestAnimationFrame(() => {
    backdrop.classList.add('open');
  });

  const cleanup = () => {
    backdrop.classList.remove('open');
    setTimeout(() => {
      backdrop.remove();
      if (typeof onClose === 'function') onClose();
    }, 280);
  };

  backdrop.addEventListener('click', (e) => {
    if (e.target === backdrop) cleanup();
  });

  const closeX = backdrop.querySelector('#modal-close-x');
  if (closeX) closeX.addEventListener('click', cleanup);

  return backdrop;
}

export function closeModal() {
  const existing = document.getElementById('active-modal-backdrop');
  if (existing) {
    existing.classList.remove('open');
    setTimeout(() => existing.remove(), 280);
  }
}
